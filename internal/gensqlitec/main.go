// Command gensqlitec writes the package sqlitec from the package sqlite.
//
// The two are the same store with a different driver: sqlite carries one
// written in Go, sqlitec the SQLite library itself, in C. So that they
// never drift apart, sqlite is the only one written by hand and sqlitec is
// copied from it, tests included, with the driver changed.
//
// It is run by go generate, from this folder. A test here fails when
// sqlitec is not what sqlite gives today.
package main

//go:generate go run .

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

const (
	source = "../../sqlite"
	target = "../../sqlitec"
	// What every file of sqlitec begins with. Without cgo the driver
	// builds but cannot open anything, so the package asks for it: the
	// build fails instead of the program.
	header = "// Code generated by internal/gensqlitec from %s; DO NOT EDIT.\n\n//go:build cgo\n\n"
)

// The driver paragraph of the package comment, as each package has it.
const (
	goDriver = `// The driver is modernc.org/sqlite, which is pure Go: no C compiler is
// needed to build, and cross compilation keeps working.
`
	cDriver = `// The driver is github.com/mattn/go-sqlite3, which is the SQLite library
// itself, in C: it needs cgo and a C compiler to build, and gives a
// somewhat smaller program than the driver written in Go that the package
// sqlite carries. The two packages are otherwise the same, and read and
// write the same files.
`
)

// What changes from one package to the other. Every change must be found
// at least once in the whole package, or the source has moved and this
// list has to move with it.
var changes = [][2]string{
	{goDriver, cDriver},
	{`_ "modernc.org/sqlite"`, `_ "github.com/mattn/go-sqlite3"`},
	{`sql.Open("sqlite", `, `sql.Open("sqlite3", `},
	{"// Package qsqlite is ", "// Package qsqlitec is "},
	{"package qsqlite\n", "package qsqlitec\n"},
	{`"qsqlite: `, `"qsqlitec: `},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gensqlitec:", err)
		os.Exit(1)
	}
}

// run leaves in the folder of sqlitec the files sqlite gives today, and
// no other Go file.
func run() error {
	files, err := generate()
	if err != nil {
		return err
	}
	old, err := filepath.Glob(filepath.Join(target, "*.go"))
	if err != nil {
		return err
	}
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(target, 0o755); err != nil {
		return err
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(target, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// generate returns the files of sqlitec, by name, as sqlite gives them
// today.
func generate() (map[string][]byte, error) {
	files, err := filepath.Glob(filepath.Join(source, "*.go"))
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no Go files in %s", source)
	}
	out := make(map[string][]byte, len(files))
	found := make([]bool, len(changes))
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		text := strings.ReplaceAll(string(data), "\r\n", "\n")
		for i, c := range changes {
			if strings.Contains(text, c[0]) {
				found[i] = true
				text = strings.ReplaceAll(text, c[0], c[1])
			}
		}
		name := filepath.Base(f)
		// Formatted again: the import of the driver sorts elsewhere.
		src, err := format.Source([]byte(fmt.Sprintf(header, "sqlite/"+name) + text))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		out[name] = src
	}
	for i, ok := range found {
		if !ok {
			return nil, fmt.Errorf("nothing to change for %q", changes[i][0])
		}
	}
	return out, nil
}
